#!/usr/bin/env node
// Cross-validation: verify that wire bytes produced by the Rust port
// (rust/pi-protocol) decode correctly with the reference Node implementation.
//
// Reads rust/pi-protocol/tests/fixtures.tsv (one `<client|server>\t<hex>` line
// per fixture, lowercase hex of a bare CBOR payload) and, for each line:
//   1. decodes the CBOR with the Node reference decoder
//   2. validates it with parseClientMessage / parseServerMessage
//   3. frames it with encodeFrame and confirms FrameDecoder yields exactly
//      one complete frame
// Exits 1 if any line fails.
//
// The fixtures are generated by scripts/generate-protocol-fixtures.mjs.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	decodeCbor,
	encodeFrame,
	FrameDecoder,
	parseClientMessage,
	parseServerMessage,
} from "../packages/protocol/src/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const fixturesPath = join(here, "../rust/pi-protocol/tests/fixtures.tsv");

function fromHex(hex) {
	if (hex.length % 2 !== 0) throw new Error(`Hex fixture must contain whole bytes: ${hex}`);
	const bytes = new Uint8Array(hex.length / 2);
	for (let index = 0; index < bytes.length; index++) {
		bytes[index] = Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16);
	}
	return bytes;
}

function checkFixture(lineNumber, kind, hex) {
	const payload = fromHex(hex);
	const value = decodeCbor(payload);
	if (kind === "client") parseClientMessage(value);
	else parseServerMessage(value);

	const frame = encodeFrame(payload);
	const frames = new FrameDecoder().push(frame);
	if (frames.length !== 1) throw new Error(`expected exactly one frame, got ${frames.length}`);
	const decoded = decodeCbor(frames[0]);
	if (kind === "client") parseClientMessage(decoded);
	else parseServerMessage(decoded);
}

const lines = readFileSync(fixturesPath, "utf8").split("\n");
const failures = [];
let total = 0;

for (let index = 0; index < lines.length; index++) {
	const line = lines[index].trim();
	if (line === "") continue;
	total++;
	const [kind, hex] = line.split("\t");
	if (kind !== "client" && kind !== "server") {
		failures.push({ line: index + 1, error: new Error(`unknown kind ${kind}`) });
		continue;
	}
	try {
		checkFixture(index + 1, kind, hex);
	} catch (error) {
		failures.push({ line: index + 1, error });
	}
}

for (const failure of failures) {
	console.error(`FAIL line ${failure.line}: ${failure.error.message}`);
}
console.log(
	`check-protocol-cross: ${total - failures.length}/${total} fixtures decoded by Node reference implementation`,
);
if (failures.length > 0) {
	process.exitCode = 1;
}
